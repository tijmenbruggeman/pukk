#!/usr/bin/env python3
"""Generate the answer shape icons (triangle, diamond, circle, square) as
LVGL A8 images in components/ui/assets/pukk_shapes.c. A8 images are drawn in
the image recolor color, so one bitmap serves every tile color."""
from pathlib import Path

SIZE = 40          # px
SUPERSAMPLE = 4    # per axis, for anti-aliasing
PAD = 2.5          # px of empty border


def triangle(x: float, y: float) -> bool:
    # Equilateral, pointing up, centred in the box.
    top, bottom = PAD + 1, SIZE - PAD - 2
    half = (bottom - top) / 3 ** 0.5
    if not top <= y <= bottom:
        return False
    w = half * (y - top) / (bottom - top)
    return abs(x - SIZE / 2) <= w


def diamond(x: float, y: float) -> bool:
    r = SIZE / 2 - PAD
    return abs(x - SIZE / 2) + abs(y - SIZE / 2) <= r


def circle(x: float, y: float) -> bool:
    r = SIZE / 2 - PAD - 1
    return (x - SIZE / 2) ** 2 + (y - SIZE / 2) ** 2 <= r * r


def square(x: float, y: float) -> bool:
    lo, hi, rad = PAD + 3, SIZE - PAD - 3, 4.0
    if not (lo <= x <= hi and lo <= y <= hi):
        return False
    cx = min(max(x, lo + rad), hi - rad)
    cy = min(max(y, lo + rad), hi - rad)
    return (x - cx) ** 2 + (y - cy) ** 2 <= rad * rad


def render(inside) -> bytes:
    out = bytearray()
    n = SUPERSAMPLE
    for py in range(SIZE):
        for px in range(SIZE):
            hits = sum(inside(px + (i + 0.5) / n, py + (j + 0.5) / n)
                       for i in range(n) for j in range(n))
            out.append(round(255 * hits / (n * n)))
    return bytes(out)


def c_image(name: str, data: bytes) -> str:
    rows = [", ".join(f"0x{b:02x}" for b in data[y * SIZE:(y + 1) * SIZE]) for y in range(SIZE)]
    body = ",\n    ".join(rows)
    return f"""static const uint8_t {name}_map[] = {{
    {body}
}};

const lv_image_dsc_t {name} = {{
    .header = {{
        .magic = LV_IMAGE_HEADER_MAGIC,
        .cf = LV_COLOR_FORMAT_A8,
        .w = {SIZE},
        .h = {SIZE},
        .stride = {SIZE},
    }},
    .data_size = sizeof({name}_map),
    .data = {name}_map,
}};
"""


def main() -> None:
    out = Path(__file__).resolve().parents[2] / "components/ui/assets/pukk_shapes.c"
    parts = ["/* Generated by tools/assets/gen_shapes.py. Do not edit. */\n#include \"lvgl.h\"\n"]
    for name, fn in [("triangle", triangle), ("diamond", diamond), ("circle", circle), ("square", square)]:
        parts.append(c_image(f"pukk_shape_{name}", render(fn)))
    out.write_text("\n".join(parts))
    print(f"{out}: {out.stat().st_size} bytes")


if __name__ == "__main__":
    main()
